bool check_equal(const char *label, const uint8_t *actual,
                 const uint8_t *expected, std::size_t size) {
    for (std::size_t i = 0; i < size; ++i) {
        if (actual[i] != expected[i]) {
            std::fprintf(stderr,
                         "%s mismatch at byte %zu: got %02x, expected %02x\n",
                         label, i, actual[i], expected[i]);
            return false;
        }
    }
    return true;
}

bool run_vector(int32_t type, const uint8_t *expected_ciphertext,
                std::size_t size) {
    uint8_t plaintext[184];
    uint8_t buffer[184];
    for (std::size_t i = 0; i < size; ++i) {
        plaintext[i] = static_cast<uint8_t>((i * 73 + 41) & 0xff);
    }

    MULTI2 *m2 = create_multi2();
    if (!m2) {
        std::fprintf(stderr, "create_multi2 failed\n");
        return false;
    }

    bool ok = true;
    if (m2->set_round(m2, 4) != 0 ||
        m2->set_system_key(m2, kSystemKey) != 0 ||
        m2->set_init_cbc(m2, kIv) != 0 ||
        m2->set_scramble_key(m2, kScrambleKey) != 0) {
        std::fprintf(stderr, "MULTI2 setup failed\n");
        ok = false;
    }

    if (ok) {
        std::memcpy(buffer, plaintext, size);
        if (m2->encrypt(m2, type, buffer, static_cast<int32_t>(size)) != 0) {
            std::fprintf(stderr, "MULTI2 encrypt failed\n");
            ok = false;
        } else {
            ok = check_equal("encrypt", buffer, expected_ciphertext, size);
        }
    }

    if (ok) {
        std::memcpy(buffer, expected_ciphertext, size);
        if (m2->decrypt(m2, type, buffer, static_cast<int32_t>(size)) != 0) {
            std::fprintf(stderr, "MULTI2 decrypt failed\n");
            ok = false;
        } else {
            ok = check_equal("decrypt", buffer, plaintext, size);
        }
    }

    m2->release(m2);
    return ok;
}

